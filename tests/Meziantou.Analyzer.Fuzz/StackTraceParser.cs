using System.Collections.Immutable;
using System.Globalization;
using System.Text.RegularExpressions;

namespace Meziantou.Analyzer.Fuzz;

/// <summary>
/// Extract the frames of the analyzer from the text of an exception, or from the output of a process that crashed (e.g. "Stack overflow.").
/// </summary>
internal static partial class StackTraceParser
{
    public static ImmutableArray<string> GetAnalyzerFrames(string text)
    {
        return [.. GetFrames(text).Where(IsAnalyzerFrame).Select(Normalize)];
    }

    /// <summary>The lines of the text that are stack frames, at most <paramref name="maxCount"/>, with the consecutive duplicates of a stack overflow collapsed.</summary>
    public static string GetFrameLines(string text, int maxCount)
    {
        var lines = new List<string>();
        string? previous = null;
        var repeatCount = 0;
        foreach (var line in FrameRegex().Matches(text).Select(match => match.Value.TrimEnd()))
        {
            if (line == previous)
            {
                repeatCount++;
                continue;
            }

            AddRepeatCount();
            if (lines.Count >= maxCount)
                break;

            lines.Add(line);
            previous = line;
        }

        AddRepeatCount();
        return string.Join('\n', lines);

        void AddRepeatCount()
        {
            if (repeatCount > 0)
            {
                lines.Add($"   ... repeated {repeatCount.ToString(CultureInfo.InvariantCulture)} more times");
                repeatCount = 0;
            }
        }
    }

    private static IEnumerable<string> GetFrames(string text) => FrameRegex().Matches(text).Select(match => match.Groups["method"].Value.Trim());

    // Meziantou.Framework.Roslyn is a source package, compiled into the analyzer assemblies
    private static bool IsAnalyzerFrame(string method)
    {
        return (method.StartsWith("Meziantou.Analyzer.", StringComparison.Ordinal) && !method.StartsWith("Meziantou.Analyzer.Fuzz.", StringComparison.Ordinal))
            || method.StartsWith("Meziantou.Framework.Roslyn.", StringComparison.Ordinal);
    }

    // The names generated by the compiler for the lambdas, the local functions and the state machines contain
    // ordinals that change when the code is edited, so they are removed to keep the signatures of the findings stable
    private static string Normalize(string method)
    {
        return string.Join('.', method.Split('.').Select(segment => segment.AsSpan().IndexOfAny('<', '>', '|') >= 0 ? DigitsRegex().Replace(segment, "") : segment));
    }

    [GeneratedRegex(@"^[ \t]*at (?<method>[^(\r\n]+)\(.*$", RegexOptions.Multiline | RegexOptions.ExplicitCapture, matchTimeoutMilliseconds: 10_000)]
    private static partial Regex FrameRegex();

    [GeneratedRegex("[0-9]+", RegexOptions.None, matchTimeoutMilliseconds: 10_000)]
    private static partial Regex DigitsRegex();
}
